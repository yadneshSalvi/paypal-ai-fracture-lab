/** Public contracts contain repository-relative paths only. Source is untrusted data. */
export const SOURCE_WORKSPACE_SCHEMA = "fracture.source-workspace/v1" as const;
export const SOURCE_GRAPH_SCHEMA = "fracture.source-graph/v1" as const;

export interface SourceImportLimits {
  maxFiles: number;
  maxEntries: number;
  maxTotalBytes: number;
  maxFileBytes: number;
  maxDepth: number;
  maxPathLength: number;
  maxParserNodes: number;
  maxSyntaxDepth: number;
  maxGraphNodes: number;
  maxGraphEdges: number;
  maxFindings: number;
  parserTimeoutMs: number;
}

export interface SourceWorkspaceConfiguration {
  /** Trusted host configuration, never imported request or model tool arguments. */
  storageRoot: string;
  allowedRoots: ReadonlyArray<{ id: string; directory: string }>;
  limits?: Partial<SourceImportLimits>;
  /** Optional trusted interpreter; only our ast.parse inspector runs. */
  pythonExecutable?: string;
  /** Additional exact credentials to exclude, supplied by trusted configuration only. */
  secretValues?: readonly string[];
}

export interface ImportSourceWorkspaceInput {
  rootId: string;
  /** "." or a portable relative directory; absolute paths are rejected. */
  path: string;
  /** SHA256 of the caller's scope and durable request identity, generated by the service. */
  requestKey: string;
}
export type SourceLanguage = "typescript" | "javascript" | "python" | "json" | "text";
export interface SourceFileManifest { path: string; hash: string; bytes: number; language: SourceLanguage }

/** One-based line/column, zero-based UTF-16 offsets and UTF-8 bytes; end is exclusive. */
export interface SourceSpan {
  path: string;
  hash: string;
  startLine: number;
  startColumn: number;
  endLine: number;
  endColumn: number;
  startOffset: number;
  endOffset: number;
  startByte: number;
  endByte: number;
}
export type StaticEvidenceType = "typescript_ast" | "python_ast" | "manifest" | "static_unresolved";
export type StaticConfidence = "syntax" | "inferred" | "unresolved";
export interface SourceEvidence { type: StaticEvidenceType; source: SourceSpan }
export type IntegrationNodeKind = "file" | "module" | "function" | "route" | "commerce_intent" | "provider_operation" | "state_write" | "fulfillment" | "webhook" | "identity" | "reconciliation" | "outbound_destination" | "declared_tool";
export interface SourceIntegrationNode {
  id: string;
  kind: IntegrationNodeKind;
  label: string;
  confidence: StaticConfidence;
  evidence: SourceEvidence;
  /** Syntax hints do not certify installed versions or supported SDK methods. */
  adapter?: "raw_http" | "apimatic_context" | "paypal_server_sdk" | "legacy_paypal" | "unresolved";
  operation?: string;
  identity?: "present" | "absent" | "unknown";
  origin?: string;
}
export type IntegrationEdgeRelation = "contains" | "imports" | "calls" | "writes" | "handles" | "supplies_identity" | "may_reconcile" | "may_fulfill" | "targets" | "unknown_target";
export interface SourceIntegrationEdge {
  id: string;
  from: string;
  to: string;
  relation: IntegrationEdgeRelation;
  confidence: StaticConfidence;
  evidence: SourceEvidence;
}
export type SourceRiskCategory = "missing_provider_identity" | "generic_identity_reliance" | "unverified_webhook" | "unknown_outcome_without_reread" | "fulfillment_without_capture_evidence" | "unresolved_payment_call";
export interface SourceRiskFinding {
  id: string;
  category: SourceRiskCategory;
  severity: "risk" | "unverified";
  title: string;
  explanation: string;
  nodeIds: readonly string[];
  evidence: readonly SourceEvidence[];
  runtimeEvidenceRequired: true;
  providerFactId?: "F9";
}
export interface SourceLanguageCoverage {
  language: SourceLanguage;
  status: "parsed" | "partial" | "unsupported";
  files: number;
  parsedFiles: number;
  limitations: readonly string[];
}
export interface SourceIntegrationGraph {
  schemaVersion: typeof SOURCE_GRAPH_SCHEMA;
  mode: "static";
  runtimeObserved: false;
  nodes: readonly SourceIntegrationNode[];
  edges: readonly SourceIntegrationEdge[];
  findings: readonly SourceRiskFinding[];
  coverage: readonly SourceLanguageCoverage[];
  limitations: readonly string[];
}
export interface DeclaredSourceTool {
  id: string;
  name: string;
  kind: "package_script" | "python_build" | "make_target" | "container_instruction";
  commandHash: string;
  source: SourceSpan;
  shellSyntax: boolean;
  outboundOrigins: readonly string[];
  trust: "untrusted_declaration";
  execution: "not_executed";
}
export interface SourceToolManifest {
  schemaVersion: "fracture.source-tools/v1";
  hash: string;
  tools: readonly DeclaredSourceTool[];
  dependencyManifests: readonly { path: string; hash: string }[];
  lockfiles: readonly { path: string; hash: string }[];
  commandsExecuted: 0;
  dependenciesInstalled: false;
}
export type SourceExclusionReason = "hidden_or_secret_path" | "dependency_tree" | "generated_tree" | "unsupported_file" | "private_storage";
export interface SourceExclusion { path: string; reason: SourceExclusionReason }
export interface SourceExecutionCapability {
  contractVersion: "fracture.source-adapter/v1";
  status: "static_only";
  arbitrarySourceExecution: false;
  requiredGates: readonly string[];
}
export interface SourceWorkspaceSnapshot {
  schemaVersion: typeof SOURCE_WORKSPACE_SCHEMA;
  id: string;
  revisionHash: string;
  manifestHash: string;
  createdAt: string;
  authorityId: string;
  files: readonly SourceFileManifest[];
  totalBytes: number;
  exclusions: readonly SourceExclusion[];
  tools: SourceToolManifest;
  graph: SourceIntegrationGraph;
  execution: SourceExecutionCapability;
}
export interface SourceChange {
  path: string;
  kind: "added" | "modified" | "deleted";
  beforeHash: string | null;
  afterHash: string | null;
  beforeBytes: number | null;
  afterBytes: number | null;
}
export interface SourceChangeReceipt {
  schemaVersion: "fracture.source-changes/v1";
  snapshotId: string;
  baselineRevisionHash: string;
  currentRevisionHash: string;
  checkedAt: string;
  unchanged: boolean;
  changes: readonly SourceChange[];
  exclusionsChanged: boolean;
  receiptHash: string;
}
/** Hook only; an implementation must independently qualify isolation before offering execution. */
export interface SourceExecutionAdapter {
  readonly contractVersion: "fracture.source-adapter/v1";
  readonly adapterId: string;
  qualify(input: {
    snapshotId: string;
    revisionHash: string;
    manifestHash: string;
    declaredEntrypoints: readonly { path: string; exportName: string }[];
  }): Promise<{
    status: "qualified" | "blocked";
    snapshotId: string;
    revisionHash: string;
    isolationReceiptHash: string | null;
    gates: readonly { name: string; passed: boolean }[];
  }>;
}
export interface SourceWorkspaceStore {
  importSnapshot(input: ImportSourceWorkspaceInput): Promise<SourceWorkspaceSnapshot>;
  getSnapshot(snapshotId: string): Promise<SourceWorkspaceSnapshot>;
  readSource(input: { snapshotId: string; path: string; expectedHash: string }): Promise<{ path: string; hash: string; content: string }>;
  checkChanges(input: { snapshotId: string }): Promise<SourceChangeReceipt>;
}
export type SourceWorkspaceErrorCode = "SOURCE_CONFIG_INVALID" | "SOURCE_PATH_INVALID" | "SOURCE_AUTHORITY_DENIED" | "SOURCE_AUTHORITY_CHANGED" | "SOURCE_SYMLINK_DENIED" | "SOURCE_SPECIAL_FILE_DENIED" | "SOURCE_HARDLINK_DENIED" | "SOURCE_LIMIT_EXCEEDED" | "SOURCE_SECRET_DETECTED" | "SOURCE_ENCODING_INVALID" | "SOURCE_CHANGED_DURING_IMPORT" | "SOURCE_PARSE_FAILED" | "SOURCE_PARSER_LIMIT" | "SOURCE_STORAGE_UNSAFE" | "SOURCE_SNAPSHOT_NOT_FOUND" | "SOURCE_SNAPSHOT_CORRUPT" | "SOURCE_HASH_MISMATCH" | "SOURCE_IMPORT_CONFLICT" | "SOURCE_IMPORT_PENDING";
export class SourceWorkspaceError extends Error {
  readonly code: SourceWorkspaceErrorCode;
  constructor(code: SourceWorkspaceErrorCode) {
    const messages: Record<SourceWorkspaceErrorCode, string> = {
      SOURCE_CONFIG_INVALID: "Source workspace host configuration is invalid.",
      SOURCE_PATH_INVALID: "Choose a portable relative directory within a configured source root.",
      SOURCE_AUTHORITY_DENIED: "This source root is not authorized by host configuration.",
      SOURCE_AUTHORITY_CHANGED: "Source authority changed; import a new snapshot.",
      SOURCE_SYMLINK_DENIED: "Source workspace symlinks are not accepted.",
      SOURCE_SPECIAL_FILE_DENIED: "Source workspaces accept regular files and directories only.",
      SOURCE_HARDLINK_DENIED: "Files with multiple hard links are not accepted.",
      SOURCE_LIMIT_EXCEEDED: "This repository exceeds a configured source import limit.",
      SOURCE_SECRET_DETECTED: "Credential-shaped source content cannot be persisted. Remove it before importing.",
      SOURCE_ENCODING_INVALID: "Source files must contain valid UTF-8 text without binary content.",
      SOURCE_CHANGED_DURING_IMPORT: "Source changed during import; retry from a stable revision.",
      SOURCE_PARSE_FAILED: "A source file could not be parsed. No snapshot was persisted.",
      SOURCE_PARSER_LIMIT: "Source inspection exceeded its parser budget. No snapshot was persisted.",
      SOURCE_STORAGE_UNSAFE: "Private snapshot storage failed its safety checks.",
      SOURCE_SNAPSHOT_NOT_FOUND: "The source snapshot is unavailable.",
      SOURCE_SNAPSHOT_CORRUPT: "Snapshot integrity verification failed.",
      SOURCE_HASH_MISMATCH: "The requested source hash does not match the immutable snapshot.",
      SOURCE_IMPORT_CONFLICT: "This import request identity is already bound to different input.",
      SOURCE_IMPORT_PENDING: "The original import is pending or interrupted. Its accepted input has been preserved.",
    };
    super(messages[code]);
    this.name = "SourceWorkspaceError";
    this.code = code;
  }
}
