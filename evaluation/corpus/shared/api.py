from __future__ import annotations
from typing import Any, Protocol
from paypal import PaypalClient

Data = dict[str, Any]

class StoreError(Exception):
    code: str
    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code

class Store(Protocol):
    def get(self, table: str, key: str) -> Data | None: ...
    def list(self, table: str) -> list[Data]: ...
    def insert(self, table: str, key: str, value: Data) -> Data: ...
    def patch(self, table: str, key: str, value: Data, expected_version: int | None = None) -> Data: ...
    def remove(self, table: str, key: str) -> None: ...
    def reserve(self, key: str, resource: str, amount_minor: int, limit_minor: int, metadata: Data) -> Data: ...

class Context(Protocol):
    client: PaypalClient
    store: Store
    def request_id(self, *parts: str) -> str: ...
    def verify(self, event: Data) -> bool: ...
